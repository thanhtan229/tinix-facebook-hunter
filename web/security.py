"""Local WebUI security helpers.

The application is intentionally bound to localhost, but a browser can still be
tricked into talking to localhost from another website.  This module provides a
per-process session cookie and an allow-list for files exposed as media previews.
"""

from __future__ import annotations

import hmac
import secrets
import threading
from pathlib import Path
from typing import Iterable

from utils import config


SESSION_COOKIE = "tinix_session"
SESSION_TOKEN = secrets.token_urlsafe(32)
MEDIA_EXTENSIONS = {
    ".jpg", ".jpeg", ".png", ".gif", ".webp", ".bmp",
    ".mp4", ".mov", ".webm", ".avi", ".mkv", ".m4v",
}

_media_roots: set[Path] = set()
_roots_lock = threading.RLock()


def valid_session(value: str | None) -> bool:
    """Return True only for the session generated by this application process."""
    if not value:
        return False
    return hmac.compare_digest(value, SESSION_TOKEN)


def register_media_root(path: str | Path) -> Path:
    """Allow media previews below a folder explicitly selected by the user."""
    root = Path(path).expanduser().resolve()
    if not root.is_dir():
        raise ValueError(f"Media root is not a directory: {root}")
    with _roots_lock:
        _media_roots.add(root)
    return root


def _configured_roots() -> Iterable[Path]:
    output_dir = config.get("output_dir", "")
    if output_dir:
        yield Path(output_dir).expanduser().resolve()


def _is_below(candidate: Path, root: Path) -> bool:
    try:
        candidate.relative_to(root)
        return True
    except ValueError:
        return False


def is_allowed_content_path(path: str | Path) -> bool:
    """Check whether a path is inside a user-approved content root."""
    candidate = Path(path).expanduser().resolve()
    with _roots_lock:
        roots = tuple(_media_roots)
    return any(_is_below(candidate, root) for root in roots)


def resolve_media_file(path: str | Path) -> Path | None:
    """Resolve an existing media file if it is below an approved root."""
    candidate = Path(path).expanduser().resolve()
    if not candidate.is_file() or candidate.suffix.lower() not in MEDIA_EXTENSIONS:
        return None

    with _roots_lock:
        roots = tuple(_media_roots)
    roots = (*roots, *_configured_roots())
    if not any(_is_below(candidate, root) for root in roots):
        return None
    return candidate
