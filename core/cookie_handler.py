"""
Tinix Facebook Down — Cookie Handler
Parses, validates, and manages Facebook authentication cookies.
"""

import re
from typing import Dict, Optional, Tuple


# Essential Facebook cookies for authentication
REQUIRED_COOKIES = ("c_user", "xs")

# Additional useful cookies
USEFUL_COOKIES = ("c_user", "xs", "datr", "fr", "sb")


def parse_cookie_string(cookie_string: str) -> Dict[str, str]:
    """
    Parse a cookie string into a dictionary.

    Supports formats:
    - Standard: "key1=value1; key2=value2; ..."
    - Newline-separated: "key1=value1\\nkey2=value2\\n..."
    - Netscape cookie file format (tab-separated)

    Returns dict of cookie name → value.
    """
    cookies = {}
    cookie_string = cookie_string.strip()

    if not cookie_string:
        return cookies

    # Detect Netscape cookie file format (starts with # or domain)
    lines = cookie_string.splitlines()
    if _is_netscape_format(lines):
        return _parse_netscape(lines)

    # Standard cookie string format: "key1=value1; key2=value2"
    # Also handles newline-separated entries
    # Normalize: replace newlines with "; "
    normalized = cookie_string.replace("\n", "; ").replace("\r", "")

    # Split by "; " or ";"
    parts = re.split(r";\s*", normalized)
    for part in parts:
        part = part.strip()
        if not part or "=" not in part:
            continue
        # Split only on first "=" (values may contain "=")
        key, _, value = part.partition("=")
        key = key.strip()
        value = value.strip()
        if key:
            cookies[key] = value

    return cookies


def _is_netscape_format(lines: list[str]) -> bool:
    """Check if lines look like Netscape cookie file format."""
    for line in lines:
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        # Netscape format: domain \t flag \t path \t secure \t expiry \t name \t value
        parts = line.split("\t")
        if len(parts) >= 7 and ".facebook.com" in parts[0]:
            return True
        return False
    return False


def _parse_netscape(lines: list[str]) -> Dict[str, str]:
    """Parse Netscape/Mozilla cookie file format."""
    cookies = {}
    for line in lines:
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        parts = line.split("\t")
        if len(parts) >= 7:
            name = parts[5].strip()
            value = parts[6].strip()
            if name:
                cookies[name] = value
    return cookies


def validate_cookies(cookies: Dict[str, str]) -> Tuple[bool, str]:
    """
    Validate that essential Facebook cookies are present.
    Returns (is_valid, message).
    """
    if not cookies:
        return False, "Không tìm thấy cookies nào"

    missing = [c for c in REQUIRED_COOKIES if c not in cookies]
    if missing:
        return False, f"Thiếu cookies bắt buộc: {', '.join(missing)}"

    # Basic validation: c_user should be numeric
    c_user = cookies.get("c_user", "")
    if not c_user.isdigit():
        return False, f"Cookie 'c_user' không hợp lệ: {c_user[:20]}"

    # xs should not be empty
    xs = cookies.get("xs", "")
    if len(xs) < 5:
        return False, "Cookie 'xs' có vẻ không hợp lệ (quá ngắn)"

    return True, f"Cookies hợp lệ (user ID: {c_user})"


def cookies_to_header(cookies: Dict[str, str]) -> str:
    """Convert cookies dict to Cookie header string."""
    return "; ".join(f"{k}={v}" for k, v in cookies.items())


def cookies_to_dict(cookies: Dict[str, str]) -> Dict[str, str]:
    """Return cookies as a dict (identity function, for clarity)."""
    return dict(cookies)


def format_cookies_for_ytdlp(cookies: Dict[str, str]) -> str:
    """
    Create a Netscape cookie file content string for yt-dlp.
    yt-dlp can read cookies from a file in Netscape format.
    """
    lines = ["# Netscape HTTP Cookie File", "# Generated by Tinix FB Down", ""]
    for name, value in cookies.items():
        # domain  flag  path  secure  expiry  name  value
        line = f".facebook.com\tTRUE\t/\tTRUE\t0\t{name}\t{value}"
        lines.append(line)
    return "\n".join(lines)
